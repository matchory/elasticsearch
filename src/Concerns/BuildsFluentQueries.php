    /**
     * Shorthand to add a "regexp" filter.
     *
     * @param string $field Name of the field to add a filter for
     * @param mixed $value Filter value. Either a string value, an array of
     *                     Elasticsearch parameters, or a callable that returns
     *                     either of the previous.
     * @param int|null $flags Enables optional operators for the regular
     *                        expression.
     * @param bool|null $caseSensitivity Allows case-insensitive matching of the
     *                                   regular expression value with the
     *                                   indexed field values when set to true.
     *                                   Default is false which means the case
     *                                   sensitivity of matching depends on the
     *                                   underlying field's mapping.
     * @param int|null $maxDeterminizedStates Maximum number of automaton states
     *                                        required for the query. Default is
     *                                        10000. Elasticsearch uses Apache
     *                                        Lucene internally to parse regular
     *                                        expressions. Lucene converts each
     *                                        regular expression to a finite
     *                                        automaton containing a number of
     *                                        determinized states. You can use
     *                                        this parameter to prevent that
     *                                        conversion from unintentionally
     *                                        consuming too many resources.
     *                                        You may need to increase this
     *                                        limit to run complex regular
     *                                        expressions.
     *
     * @return $this
     * @see https://www.elastic.co/guide/en/elasticsearch/reference/current/query-dsl-regexp-query.html
     * @see https://www.elastic.co/guide/en/elasticsearch/reference/current/regexp-syntax.html#regexp-optional-operators
     */
    public function regexpFilter(
        string $field,
        mixed $value,
        ?int $flags = null,
        ?bool $caseSensitivity = null,
        ?int $maxDeterminizedStates = null,
    ): static {
        $value = value($value, $this, $field);

        if (is_array($value) || (
            $flags === null
                && $caseSensitivity === null
                && $maxDeterminizedStates === null
        )) {
            return $this->filter('regexp', [
                $field => $value,
            ]);
        }

        $parameters = [
            'value' => $value,
        ];

        $stringFlags = $this->resolveRegexpFlags($flags ?? 0);

        if ($stringFlags) {
            $parameters['flags'] = $stringFlags;
        }

        if ($caseSensitivity !== null) {
            $parameters['case_insensitive'] = $caseSensitivity;
        }

        if ($maxDeterminizedStates !== null) {
            $parameters['max_determinized_states'] = $maxDeterminizedStates;
        }

        return $this->filter('regexp', [
            $field => $parameters,
        ]);
    }

    private function resolveRegexpFlags(int $flags): ?string
    {
        $stringFlags = [];

        if ($flags & Builder::REGEXP_FLAG_ALL) {
            $stringFlags[] = 'ALL';
        }

        if ($flags & Builder::REGEXP_FLAG_COMPLEMENT) {
            $stringFlags[] = 'COMPLEMENT';
        }

        if ($flags & Builder::REGEXP_FLAG_INTERVAL) {
            $stringFlags[] = 'INTERVAL';
        }

        if ($flags & Builder::REGEXP_FLAG_INTERSECTION) {
            $stringFlags[] = 'INTERSECTION';
        }

        if ($flags & Builder::REGEXP_FLAG_ANYSTRING) {
            $stringFlags[] = 'ANYSTRING';
        }

        if (empty($stringFlags)) {
            return null;
        }

        return implode('|', $stringFlags);
    }

