    /**
     * Search the entire document fields
     *
     * @param string|null $queryString
     * @param callable|array|null $settings
     * @param int|null $boost
     *
     * @return $this
     */
    public function search(
        ?string $queryString = null,
        callable|array|null $settings = null,
        ?int $boost = null,
    ): static {
        if (!$queryString) {
            return $this;
        }

        $params = ['query' => $queryString];
        $fields = [];

        if (is_callable($settings)) {
            $config = new class {
                public ?int $boost = null;

                public array $fields = [];

                public function boost(int $boost): self
                {
                    $this->boost = $boost;

                    return $this;
                }

                public function fields(array $fields): self
                {
                    foreach ($fields as $field => $weight) {
                        $this->fields[] = $weight > 1 ? "{$field}^{$weight}" : $field;
                    }

                    return $this;
                }
            };

            $settings($config);
            $boost = $config->boost ?? $boost;
            $fields = $config->fields;
        }

        if ($boost !== null && $boost > 1) {
            $params['boost'] = $boost;
        }

        if ($fields) {
            $params['fields'] = $fields;
        }

        $this->must[] = ['query_string' => $params];

        return $this;
    }

